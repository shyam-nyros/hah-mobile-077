import {
  View,
  Text,
  TouchableOpacity,
  FlatList,
  Dimensions,
  Image,
} from 'react-native';
import tw from 'twrnc';
import {truncateText} from '../../utils/helpers';
import {useNavigation} from '@react-navigation/native';

import musicicon from '../../assets/images/musicoutlineicon.png';
import videoicon from '../../assets/images/blueplayicon.png';
import ebookicon from '../../assets/images/bluebookicon.png';
import bookcoverImg from '../../assets/images/defaults/bookplaceholder.png';
import videocoverImg from '../../assets/images/defaults/videothumbnail.png';
import audiocoverImg from '../../assets/images/podcastplaceholder.png';
import {useSelector} from 'react-redux';
import {useLibraryItemViewedAPIMutation} from '../../features/library/libraryApiSlice';

const {height, width} = Dimensions.get('window');

const CategoryItem = ({categoryData, handleCategoryClick}) => {
  const {profession, interestedContent} = useSelector(state => state.auth);
  const navigation = useNavigation();

  const [libraryItemViewedAPI] = useLibraryItemViewedAPIMutation();

  const getLibraryItemIconType = libraryType => {
    if (libraryType === 'ebook') {
      return ebookicon;
    } else if (libraryType === 'video') {
      return videoicon;
    } else {
      return musicicon;
    }
  };

  const getCoverImage = libraryType => {
    if (libraryType === 'ebook') {
      return bookcoverImg;
    } else if (libraryType === 'video') {
      return videocoverImg;
    } else {
      return audiocoverImg;
    }
  };

  const handleNavigationByLibraryItemType = async (libraryType, id) => {
    libraryItemViewed(id);
    if (libraryType === 'ebook') {
      navigation.navigate('BookDetails', {libraryItemId: id});
    } else if (libraryType === 'video') {
      navigation.navigate('VideoDetails', {libraryItemId: id});
    } else {
      navigation.navigate('PodcastDetails', {libraryItemId: id});
    }
  };

  const libraryItemViewed = async id => {
    try {
      const res = await libraryItemViewedAPI(id).unwrap();
    } catch (error) {}
  };

  const renderItem = ({item}) => (
    <TouchableOpacity
      onPress={() => handleNavigationByLibraryItemType(item?.type, item._id)}
      style={tw`mr-2 flex-1`}
      key={item._id}>
      <Image
        source={getLibraryItemIconType(item?.type)}
        style={tw`w-4 h-4 bg-white bg-opacity-90 rounded-full absolute top-1 left-1 z-10`}
        resizeMode="contain"
      />
      {/* generated by AI */}
      {item?.aigenerated && (
        <Image
          source={
            item?.ai_cover_image
              ? {uri: item?.ai_cover_image}
              : getCoverImage(item?.type)
          }
          style={tw`bg-[#D9D9D9] h-[106px] w-[125px] rounded-[12px]`}
        />
      )}
      {/* not generated by AI */}
      {!item?.aigenerated && (
        <Image
          source={
            item?.cover_image
              ? {uri: item?.cover_image}
              : getCoverImage(item?.type)
          }
          style={tw`bg-[#D9D9D9] h-[106px] w-[125px] rounded-[12px]`}
        />
      )}
      <View style={tw`mt-1`}>
        <Text
          style={tw`text-[14px] text-[#0077B6] font-medium`}
          numberOfLines={2}
          ellipsizeMode="tail">
          {truncateText(item?.title, 15)}
        </Text>
        <Text
          style={tw`text-[12px] text-[#040641] opacity-60 font-medium`}
          numberOfLines={1}>
          {item?.author?.first_name || 'N/A'}
          {item?.author?.last_name ? ` ${item.author?.last_name}` : ''}
        </Text>
      </View>
    </TouchableOpacity>
  );

  return (
    <View style={tw`mb-6 mx-4`} key={categoryData?.category?._id}>
      <View style={tw`flex-row justify-between items-center `}>
        {categoryData?.libraries?.length > 0 && (
          <Text style={tw`text-[15px] text-[#040641] font-semibold pb-2`}>
            {categoryData?.category?.name}
          </Text>
        )}
        {categoryData?.libraries?.length > 0 && categoryData.category._id && (
          <TouchableOpacity
            onPress={() => handleCategoryClick(categoryData?.category?._id)}
            style={tw`pb-2`}>
            <Text style={tw`text-[13px] text-[#040641] opacity-50`}>
              See all {'>'}
            </Text>
          </TouchableOpacity>
        )}
      </View>

      {/* show this text if the category matches with the user selected interests */}
      {interestedContent.map(
        item =>
          item?._id === categoryData?.category?._id && (
            <Text
              key={item._id}
              style={tw`text-[13px] text-[#040641] opacity-70 mb-4`}>
              Because your job title is {profession.name}
            </Text>
          ),
      )}

      <FlatList
        data={categoryData?.libraries}
        renderItem={renderItem}
        keyExtractor={item => item._id}
        horizontal
        showsHorizontalScrollIndicator={false}
      />
    </View>
  );
};

export default CategoryItem;
