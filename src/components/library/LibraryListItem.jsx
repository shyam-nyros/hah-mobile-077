import {useNavigation} from '@react-navigation/native';
import {View, TouchableOpacity, Image, Text, StyleSheet} from 'react-native';
import tw from 'twrnc';
import musicicon from '../../assets/images/musicoutlineicon.png';
import videoicon from '../../assets/images/blueplayicon.png';
import ebookicon from '../../assets/images/bluebookicon.png';

import bookcoverImg from '../../assets/images/defaults/bookplaceholder.png';
import videocoverImg from '../../assets/images/defaults/videothumbnail.png';
import audiocoverImg from '../../assets/images/podcastplaceholder.png';

import {
  widthPercentageToDP as wp,
  heightPercentageToDP as hp,
} from 'react-native-responsive-screen';
import {truncateText} from '../../utils/helpers';
import {useState} from 'react';
import {
  useLibraryItemViewedAPIMutation,
  useRemoveBookMarksAPIMutation,
  useSaveBookMarksAPIMutation,
} from '../../features/library/libraryApiSlice';

const LibraryListItem = ({libraryInfo}) => {
  const navigation = useNavigation();
  const [saveBookMarksAPI] = useSaveBookMarksAPIMutation();
  const [removeBookMarksAPI] = useRemoveBookMarksAPIMutation();

  const [libraryItemViewedAPI] = useLibraryItemViewedAPIMutation();

  // old
  // const getCoverImage = mimetype => {
  //   if (mimetype === 'audio/mpeg') {
  //     return audiocoverImg;
  //   } else if (mimetype === 'video/mp4') {
  //     return videocoverImg;
  //   } else {
  //     return bookcoverImg;
  //   }
  // };

  const getCoverImage = libraryItemType => {
    if (libraryItemType === 'audio') {
      return audiocoverImg;
    } else if (libraryItemType === 'video') {
      return videocoverImg;
    } else {
      return bookcoverImg;
    }
  };

  // const getLibraryItemIconType = mimetype => {
  //   if (mimetype === 'application/pdf') {
  //     return ebookicon;
  //   } else if (mimetype === 'video/mp4') {
  //     return videoicon;
  //   } else {
  //     return musicicon;
  //   }
  // };

  const getLibraryItemIconType = libraryItemType => {
    if (libraryItemType === 'ebook') {
      return ebookicon;
    } else if (libraryItemType === 'video') {
      return videoicon;
    } else {
      return musicicon;
    }
  };

  // old
  // const handleNavigation = (mimetype, id) => {
  //   if (mimetype.includes('audio/')) {
  //     navigation.navigate('PodcastDetails', {libraryItemId: id});
  //   } else if (mimetype.includes('video/')) {
  //     navigation.navigate('VideoDetails', {libraryItemId: id});
  //   } else if (mimetype === 'application/pdf') {
  //     navigation.navigate('BookDetails', {libraryItemId: id});
  //   }
  // };

  const handleNavigation = async (libraryItemType, id) => {
    libraryItemViewed(id);
    if (libraryItemType === 'audio') {
      navigation.navigate('PodcastDetails', {libraryItemId: id});
    } else if (libraryItemType === 'video') {
      navigation.navigate('VideoDetails', {libraryItemId: id});
    } else if (libraryItemType === 'ebook') {
      navigation.navigate('BookDetails', {libraryItemId: id});
    }
  };

  const libraryItemViewed = async id => {
    try {
      const res = await libraryItemViewedAPI(id).unwrap();
    } catch (error) {}
  };

  const handleBookmarkToggle = async () => {
    try {
      if (libraryInfo.user_bookmarked) {
        await removeBookMarksAPI(libraryInfo._id);
      } else {
        await saveBookMarksAPI(libraryInfo._id);
      }
    } catch (error) {
      console.error('Failed to toggle bookmark:', error);
    }
  };

  return (
    <View>
      <View style={tw`mt-4 mb-6`}>
        <View style={tw`flex-row flex-wrap justify-between`}>
          <View key={libraryInfo._id} style={styles.cardcontainer}>
            <TouchableOpacity
              onPress={() =>
                handleNavigation(libraryInfo?.type, libraryInfo._id)
              }>
              <Image
                source={getLibraryItemIconType(libraryInfo?.type)}
                style={tw`w-4 h-4 bg-white bg-opacity-90 rounded-full absolute top-1 left-1 z-10`}
                resizeMode="contain"
              />
              {/* generated by AI */}
              {libraryInfo?.aigenerated && (
                <Image
                  source={
                    libraryInfo?.ai_cover_image
                      ? {uri: libraryInfo?.ai_cover_image}
                      : getCoverImage(libraryInfo?.type)
                  }
                  style={[tw`rounded-[10px]`, styles.img]}
                />
              )}
              {/* not generated by AI */}
              {!libraryInfo?.aigenerated && (
                <Image
                  source={
                    libraryInfo.cover_image
                      ? {uri: libraryInfo.cover_image}
                      : getCoverImage(libraryInfo?.type)
                  }
                  style={[tw`rounded-[10px]`, styles.img]}
                />
              )}
              <View
                style={tw`p-1 rounded-full bg-white absolute right-2 top-2`}></View>
              <View style={tw`mx-2`}>
                <View
                  style={tw`p-1 px-4 rounded-full bg-[#0077B6] absolute right-0 -top-9`}>
                  <Text style={tw`text-[12px] text-white font-medium`}>
                    {` $ ${libraryInfo.price?.$numberDecimal}`}
                  </Text>
                </View>
              </View>
            </TouchableOpacity>

            <View style={tw`mt-2 rounded-b-10 w-auto`}>
              <View style={tw`flex-row justify-between`}>
                <TouchableOpacity
                  onPress={() =>
                    // handleNavigation(
                    //   libraryInfo.attachment.mimetype,
                    //   libraryInfo._id,
                    // )
                    handleNavigation(libraryInfo?.type, libraryInfo._id)
                  }>
                  <Text
                    style={[
                      tw`text-[#0077B6] font-medium flex-wrap`,
                      styles.text,
                    ]}>
                    {truncateText(libraryInfo.title, 17)}
                  </Text>
                </TouchableOpacity>
                <TouchableOpacity onPress={handleBookmarkToggle}>
                  <Image
                    source={
                      libraryInfo.user_bookmarked
                        ? require('../../assets/images/saveactiveicon.png')
                        : require('../../assets/images/saveicon.png')
                    }
                    style={tw`h-6 w-6`}
                  />
                </TouchableOpacity>
              </View>
              <Text
                style={[
                  tw`text-[#040641] font-medium opacity-80`,
                  styles.textauthor,
                ]}>
                {libraryInfo?.author?.first_name || 'N/A'}
                {libraryInfo?.author?.last_name
                  ? ` ${libraryInfo.author?.last_name}`
                  : ''}
              </Text>
            </View>
          </View>
        </View>
      </View>
    </View>
  );
};

export default LibraryListItem;

const styles = StyleSheet.create({
  img: {
    width: wp('44.5%'),
    height: hp('20.1%'),
  },
  text: {
    fontSize: hp('1.8%'),
    fontWeight: '600',
  },
  textauthor: {
    marginTop: -2,
    fontSize: hp('1.5%'),
  },
  cardcontainer: {
    width: wp('44.5%'),
  },
});
