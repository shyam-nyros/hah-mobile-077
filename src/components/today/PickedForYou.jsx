import React, {useRef, useState} from 'react';
import {
  FlatList,
  Image,
  Text,
  TouchableOpacity,
  Animated,
  View,
  Dimensions,
} from 'react-native';
import tw from 'twrnc';
import {useSelector} from 'react-redux';
import {useNavigation} from '@react-navigation/native';
import LoadingSpinner from '../LoadingSpinner';
import {truncateText} from '../../utils/helpers';
import ShimmerPlaceholder from 'react-native-shimmer-placeholder';
import LinearGradient from 'react-native-linear-gradient';
import {usePickedForYouAPIQuery} from '../../features/home/homeApiSlice';

import musicicon from '../../assets/images/musicoutlineicon.png';
import videoicon from '../../assets/images/blueplayicon.png';
import ebookicon from '../../assets/images/bluebookicon.png';

import bookcoverImg from '../../assets/images/defaults/bookplaceholder.png';
import videocoverImg from '../../assets/images/defaults/videothumbnail.png';
import audiocoverImg from '../../assets/images/podcastplaceholder.png';
import {useLibraryItemViewedAPIMutation} from '../../features/library/libraryApiSlice';

const PickedForYou = () => {
  const navigation = useNavigation();
  const {firstName} = useSelector(state => state.auth);

  const flatListRef = useRef(null);
  const [libraryItemViewedAPI] = useLibraryItemViewedAPIMutation();

  const {
    data: picked,
    isLoading: pickedIsLoading,
    isFetching: pickedIsFetching,
    isError: pickedIsError,
  } = usePickedForYouAPIQuery();

  // Placeholder based on item type when no image is available
  const getPlaceholderImage = libraryType => {
    if (libraryType === 'ebook') {
      return bookcoverImg;
    } else if (libraryType === 'video') {
      return videocoverImg;
    } else {
      return audiocoverImg;
    }
  };

  const handleNavigationByLibraryItemType = async (libraryType, id) => {
    libraryItemViewed(id);
    if (libraryType === 'ebook') {
      navigation.navigate('BookDetails', {libraryItemId: id});
    } else if (libraryType === 'video') {
      navigation.navigate('VideoDetails', {libraryItemId: id});
    } else {
      navigation.navigate('PodcastDetails', {libraryItemId: id});
    }
  };

  const getLibraryItemIconType = libraryType => {
    if (libraryType === 'ebook') {
      return ebookicon;
    } else if (libraryType === 'video') {
      return videoicon;
    } else {
      return musicicon;
    }
  };

  const libraryItemViewed = async id => {
    try {
      const res = await libraryItemViewedAPI(id).unwrap();
    } catch (error) {}
  };

  const renderItem = ({item, index}) => (
    <Animated.View>
      <TouchableOpacity
        key={item._id}
        onPress={() => handleNavigationByLibraryItemType(item?.type, item._id)}>
        <View style={tw`bg-[#D9D9D9] h-[83px] w-[140px] rounded-[10px] mr-3`}>
          <View>
            {/* generated by AI */}
            {item?.aigenerated && (
              <Image
                source={
                  item?.ai_cover_image
                    ? {uri: item.ai_cover_image}
                    : getPlaceholderImage(item?.type)
                }
                style={tw`w-full h-21 mr-1 rounded-[10px]`}
              />
            )}
            {/* not generated by AI */}
            {!item?.aigenerated && (
              <Image
                source={
                  item?.cover_image
                    ? {uri: item?.cover_image}
                    : getPlaceholderImage(item?.type)
                }
                style={tw`w-full h-21 mr-1 rounded-[10px]`}
              />
            )}
            {item?.type && (
              <Image
                source={getLibraryItemIconType(item?.type)}
                style={tw`absolute top-1 left-1 w-4 h-4 bg-white bg-opacity-90 rounded-full`}
                resizeMode="contain"
              />
            )}
          </View>
        </View>
        <View
          style={tw`mt-1 rounded-bl-[10px] rounded-br-[10px] w-[140px] p-2`}>
          <TouchableOpacity
            onPress={() =>
              handleNavigationByLibraryItemType(item?.type, item._id)
            }>
            <Text
              style={tw`text-[14px] text-[#0077B6] font-medium`}
              numberOfLines={1}
              ellipsizeMode="tail">
              {item.title}
            </Text>
          </TouchableOpacity>
          <Text style={tw`text-[11px] text-[#040641] opacity-70 font-medium`}>
            {truncateText(item?.description, 22)}
          </Text>
          <Text style={tw`text-[11px] text-[#040641] opacity-40 mb-2`}>
            {item?.category && item?.category?.length > 0
              ? item?.category?.join(', ')
              : ''}
          </Text>
        </View>
      </TouchableOpacity>
    </Animated.View>
  );

  const renderShimmerPlaceholder = () => (
    <View style={tw`mb-4 gap-3 justify-between flex-row`}>
      {[...Array(3)].map((_, index) => (
        <View key={index} style={tw`h-[120px] w-[140px]`}>
          <ShimmerPlaceholder
            style={tw`h-[83px] w-[140px] rounded-[10px] mb-2`}
            shimmerColors={['#e0e0e0', '#f2f2f2', '#e0e0e0']}
            LinearGradient={LinearGradient}
          />
          <ShimmerPlaceholder
            style={tw`h-[16px] w-[100px] rounded-[4px] mb-1`}
            shimmerColors={['#e0e0e0', '#f2f2f2', '#e0e0e0']}
            LinearGradient={LinearGradient}
          />
          <ShimmerPlaceholder
            style={tw`h-[12px] w-[70px] rounded-[4px]`}
            shimmerColors={['#e0e0e0', '#f2f2f2', '#e0e0e0']}
            LinearGradient={LinearGradient}
          />
        </View>
      ))}
    </View>
  );

  return (
    <View style={tw`mt-1`}>
      <View style={tw`flex-row justify-between items-center `}>
        <View style={tw`flex-row items-center`}>
          <Image
            source={require('../../assets/images/pickicon.png')}
            style={tw`w-[17px] h-[17px] mr-1`}
          />
          <Text style={tw`text-[16px] text-[#040641] font-semibold`}>
            Picked for you, {firstName}!
          </Text>
        </View>
        <TouchableOpacity onPress={() => navigation.navigate('Library')}>
          <Text
            style={tw`text-[13px] md:text-[14px] pb-[8px] pb-2 lg:text-[14px] text-[#040641] opacity-50`}>
            See all {'>'}
          </Text>
        </TouchableOpacity>
      </View>

      {pickedIsLoading || pickedIsFetching ? (
        renderShimmerPlaceholder()
      ) : pickedIsError ? (
        <View style={tw`flex-1 mb-2 mt-2 justify-center items-center`}>
          <Text style={tw`text-gray-500`}>Failed to load Picked for you</Text>
        </View>
      ) : picked.libraries.length === 0 ? (
        <View style={tw`flex-1 mb-2 mt-2 justify-center items-center`}>
          <Text style={tw`text-gray-500`}>No Picked for you</Text>
        </View>
      ) : (
        <View>
          <Text
            style={tw`text-[13px] md:text-[14px] lg:text-[14px] text-[#040641] opacity-70 mb-4`}>
            {picked?.interest_text}
          </Text>
          <FlatList
            ref={flatListRef}
            data={picked?.libraries}
            renderItem={renderItem}
            keyExtractor={item => item._id}
            horizontal
            showsHorizontalScrollIndicator={false}
          />
        </View>
      )}
    </View>
  );
};

export default PickedForYou;
